# AND
print(True and True)
print(True and False)
print(False and True)
print(False and False, "\n")

# OR
print(True or True)
print(True or False)
print(False or True)
print(False or False, "\n")

# NOT

print(not True)
print(not False, "\n")

# Ejercicio con AND

print(5 > 3 and 2 < 4)
print(5 > 3 and 5 < 4)
print(2 > 3 and 2 < 4)
print(2 > 3 and 5 < 4, "\n")

# Ejercicio con OR

print(3 == 3 or 2 > 4)
print(3 > 1 or 4 < 1)
print(1 > 4 or 2 < 3)
print(1 != 1 or 2 > 3, "\n")

print(not 5 > 3)
print(not 1 == 2)