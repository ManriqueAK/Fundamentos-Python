# Asignación =
x = 5
print(x)

# Asignación con suma
x += 2
print(x)

# Asignación con resta
x -= 3
print(x)

# Asignación con prodcuto
x *= 4
print(x)

# Asignación con división
x /= 2
print(x)

# Asignación con división entera
x //= 2
print(x)

# Asignación con módulo
x %= 3
print(x)

# Asignación con exponenciación
x **= 2
print(x)


